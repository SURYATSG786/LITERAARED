def strip_latin_loanwords(text: str) -> str:
    """Replace common Latin loanwords that slipped into native strings."""
    replacements = [
        (r"\bAI\b", ""),
        (r"\bXP\b", ""),
        (r"\bCAT\b", ""),
        (r"\bDOG\b", ""),
        (r"\bSUN\b", ""),
        (r"\bHAT\b", ""),
        (r"\bBAG\b", ""),
        (r"\barticle\b", ""),
        (r"\bapple\b", ""),
        (r"\bgo\b", ""),
        (r"\bgoing\b", ""),
        (r"\bwrote\b", ""),
        (r"[A-Za-z]+", ""),
    ]
    out = text
    for pat, rep in replacements:
        out = re.sub(pat, rep, out, flags=re.I)
    out = re.sub(r"\s{2,}", " ", out).strip(" -–—:|/")
    return out.strip()


