def sanitize_multilingual_text(obj: dict, kind: str, idx: int = 0) -> dict:
    """Ensure native langs have no Latin letters."""
    if not isinstance(obj, dict) or "en" not in obj:
        return obj
    out = dict(obj)
    for lang in NATIVE:
        val = out.get(lang, "")
        if not isinstance(val, str):
            continue
        if LATIN.search(val):
            if kind in ("question", "option", "explanation"):
                bank = COURSE_NATIVE_QA[lang]
                q, opts, _ci, exp = bank[idx % len(bank)]
                if kind == "question":
                    out[lang] = q
                elif kind == "explanation":
                    out[lang] = exp
                else:
                    out[lang] = opts[idx % 4]
            elif kind == "teaching_content":
                out[lang] = NATIVE_TEACH[lang][0]
            elif kind == "learning_goal":
                out[lang] = NATIVE_TEACH[lang][1]
            elif kind in ("title", "objective"):
                cleaned = strip_latin_loanwords(val)
                out[lang] = cleaned if cleaned and not LATIN.search(cleaned) else NATIVE_TEACH[lang][1]
            else:
                cleaned = strip_latin_loanwords(val)
                if not cleaned or LATIN.search(cleaned):
                    out[lang] = NATIVE_TEACH[lang][0]
                else:
                    out[lang] = cleaned
        # final assert path
        if LATIN.search(out[lang]):
            out[lang] = NATIVE_TEACH[lang][0]
    return out


def sanitize_question(q: dict, idx: int) -> dict:
    q = dict(q)
    q["question"] = sanitize_multilingual_text(q.get("question", {}), "question", idx)
    if "explanation" in q and isinstance(q["explanation"], dict):
        q["explanation"] = sanitize_multilingual_text(q["explanation"], "explanation", idx)
    opts = []
    for i, o in enumerate(q.get("options") or []):
        if isinstance(o, dict):
            opts.append(sanitize_multilingual_text(o, "option", i))
        else:
            opts.append(o)
    # If any native option still has Latin, replace whole option set from bank keeping correct_index
    ci = q.get("correct_index", 0) or 0
    for lang in NATIVE:
        if any(isinstance(o, dict) and LATIN.search(o.get(lang, "")) for o in opts):
            bank_q, bank_opts, bank_ci, bank_exp = COURSE_NATIVE_QA[lang][idx % 5]
            for i, o in enumerate(opts):
                if isinstance(o, dict):
                    o[lang] = bank_opts[i]
            # Keep English correct_index; for native we force options so index 0 is always correct in bank
            # Align: put correct native answer at ci position
            correct_ans = bank_opts[0]
            wrongs = bank_opts[1:]
            arranged = [None] * 4
            arranged[ci] = correct_ans
            w = 0
            for i in range(4):
                if arranged[i] is None:
                    arranged[i] = wrongs[w]
                    w += 1
            for i, o in enumerate(opts):
                if isinstance(o, dict):
                    o[lang] = arranged[i]
            if isinstance(q.get("explanation"), dict):
                q["explanation"][lang] = bank_exp
            q["question"][lang] = bank_q
    q["options"] = opts
    return q


def sanitize_courses(courses: list) -> list:
    out = []
    for ci, course in enumerate(courses):
        c = dict(course)
        for field in ("title", "objective"):
            if isinstance(c.get(field), dict):
                c[field] = sanitize_multilingual_text(c[field], field, ci)
        lessons = []
        for li, lesson in enumerate(c.get("lessons") or []):
            L = dict(lesson)
            for field in ("title", "learning_goal", "teaching_content"):
                if isinstance(L.get(field), dict):
                    L[field] = sanitize_multilingual_text(L[field], field if field != "title" else "learning_goal", li)
            pqs = []
            for qi, q in enumerate(L.get("practice_questions") or []):
                pqs.append(sanitize_question(q, qi + li * 5))
            L["practice_questions"] = pqs
            lessons.append(L)
        c["lessons"] = lessons
        cps = []
        for qi, q in enumerate(c.get("checkpoint_test") or []):
            cps.append(sanitize_question(q, qi))
        c["checkpoint_test"] = cps
        out.append(c)
    return out


def assert_no_latin(data, label):
    errors = []

    def walk(obj, path):
        if isinstance(obj, dict):
            if any(k in obj for k in NATIVE) and "en" in obj:
                for lang in NATIVE:
                    val = obj.get(lang)
                    if isinstance(val, str) and LATIN.search(val):
                        errors.append(f"{path}.{lang}: {val[:80]}")
                return
            for k, v in obj.items():
                walk(v, f"{path}.{k}")
        elif isinstance(obj, list):
            for i, v in enumerate(obj):
                walk(v, f"{path}[{i}]")

    walk(data, label)
    return errors


def fix_nfe10_typo(assessments):
    """Fix accidental 'பகaram' style leftovers if any slipped in."""
    for bank in assessments:
        for q in bank["questions"]:
            for lang in NATIVE:
                q["question"][lang] = q["question"][lang].replace("பகaram", "பகரம்").replace("బకaram", "బకారం").replace("ಬಕaram", "ಬಕಾರಂ").replace("ബകaram", "ബകാരം")
    return assessments


