def walk_i18n(obj, path, visit):
    if isinstance(obj, dict):
        if "en" in obj and any(k in obj for k in NATIVE):
            visit(obj, path)
            return
        for k, v in obj.items():
            walk_i18n(v, f"{path}.{k}", visit)
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            walk_i18n(v, f"{path}[{i}]", visit)


def validate_foundation_question(q, location, errors):
    """Catch the known localized-question/English-phonics-answer corruption."""
    options = q.get("options") or []
    correct = q.get("correct_index")
    if not isinstance(correct, int) or not (0 <= correct < len(options)):
        return
    answer = options[correct]
    question = q.get("question") or {}
    for lang in NATIVE:
        text = question.get(lang) or ""
        correct_text = (answer.get(lang) or "").strip()
        if any(term in text for term in COLOR_TERMS[lang]) and correct_text not in COLOR_ANSWERS[lang]:
            errors.append(
                f"{location}: {lang} color question has non-color answer {correct_text!r}"
            )
        if any(term in text for term in OPPOSITE_TERMS[lang]) and correct_text in BAD_SOUND_ANSWERS[lang]:
            errors.append(
                f"{location}: {lang} opposite question has sound answer {correct_text!r}"
            )


def validate_all(assessments, courses):
    errors = []

    for bank in assessments:
        level = bank["education_level"]
        qs = bank["questions"]
        if len(qs) != 10:
            errors.append(f"{level}: expected 10 questions, got {len(qs)}")
        cis = [q["correct_index"] for q in qs]
        if sorted(set(cis)) != [0, 1, 2, 3]:
            errors.append(f"{level}: correct_index must use all of 0-3, got {cis}")
        for q in qs:
            if not (0 <= q["correct_index"] < 4):
                errors.append(f"{q['id']}: bad correct_index")
            for lang in NATIVE:
                if LATIN.search(q["question"][lang]):
                    errors.append(f"{q['id']} question.{lang} has Latin")
                for i, opt in enumerate(q["options"]):
                    if LATIN.search(opt[lang]):
                        errors.append(f"{q['id']} opt{i}.{lang} has Latin")
                    if PLACEHOLDER_OPT.match(opt[lang].strip()) or PLACEHOLDER_OPT.match(opt["en"].strip()):
                        errors.append(f"{q['id']} placeholder option")

    # Critical: Tamil rhyme never பூனை→தொப்பி
    ps = next(b for b in assessments if b["education_level"] == "Primary School")
    ps6 = next(q for q in ps["questions"] if q["id"] == "ps-6")
    if "பூனை" in ps6["question"]["ta"] and ps6["options"][ps6["correct_index"]]["ta"] == "தொப்பி":
        errors.append("CRITICAL: ps-6 Tamil still uses பூனை→தொப்பி")
    if ps6["options"][ps6["correct_index"]]["ta"] == "தொப்பி":
        errors.append("CRITICAL: ps-6 correct Tamil answer is தொப்பி")
    if ps6["options"][ps6["correct_index"]]["en"] != "Hat":
        errors.append("ps-6 English correct should remain Hat (literacy rhyme)")
    if ps6["options"][ps6["correct_index"]]["ta"] not in {"பல்", "வளர்", "கானம்", "கல்"}:
        # allow known good rhyme answers
        good = {"பல்", "வளர்", "கானம்"}
        if ps6["options"][ps6["correct_index"]]["ta"] not in good:
            errors.append(f"ps-6 Tamil correct not a known rhyme: {ps6['options'][ps6['correct_index']]['ta']}")

    for course in courses:
        path = course["path"]
        if len(course["lessons"]) != 4:
            errors.append(f"{course['id']}: need 4 lessons")
        for li, L in enumerate(course["lessons"]):
            pqs = L.get("practice_questions") or []
            if path in {"beginner", "intermediate", "advanced", "foundation"} and len(pqs) != 5:
                errors.append(f"{course['id']} L{li+1}: need 5 practice, got {len(pqs)}")
            if path == "foundation" and pqs and len({q.get("correct_index") for q in pqs}) == 1:
                errors.append(f"{course['id']} L{li+1}: foundation answers all use one index")
            for q in pqs:
                for lang in NATIVE:
                    blob = q.get("question", {})
                    if LATIN.search(blob.get(lang) or ""):
                        errors.append(f"{q.get('id')} question.{lang} Latin")
                    for opt in q.get("options", []):
                        if LATIN.search(opt.get(lang) or ""):
                            errors.append(f"{q.get('id')} option.{lang} Latin")
                        if PLACEHOLDER_OPT.match((opt.get(lang) or "").strip()) or PLACEHOLDER_OPT.match(
                            (opt.get("en") or "").strip()
                        ):
                            errors.append(f"{q.get('id')} placeholder option")
                # ban பூனை correct→தொப்பி pattern
                qta = q.get("question", {}).get("ta", "")
                if "பூனை" in qta and ("ஓசை" in qta or "rhyme" in q.get("question", {}).get("en", "").lower()):
                    ans = q["options"][q["correct_index"]].get("ta")
                    if ans == "தொப்பி":
                        errors.append(f"{q.get('id')}: Tamil பூனை→தொப்பி rhyme")
                if path == "foundation":
                    validate_foundation_question(q, f"{course['id']} L{li+1}/{q.get('id')}", errors)
        ckpt = course.get("checkpoint_test") or []
        if len(ckpt) != 10:
            errors.append(f"{course['id']}: need 10 checkpoint, got {len(ckpt)}")
        if path == "foundation" and {q.get("correct_index") for q in ckpt} != {0, 1, 2, 3}:
            errors.append(f"{course['id']}: foundation checkpoint must use indices 0-3")
        for q in ckpt:
            for lang in NATIVE:
                if LATIN.search(q.get("question", {}).get(lang) or ""):
                    errors.append(f"{q.get('id')} cp question.{lang} Latin")
                for opt in q.get("options", []):
                    if LATIN.search(opt.get(lang) or ""):
                        errors.append(f"{q.get('id')} cp option.{lang} Latin")
                    if PLACEHOLDER_OPT.match((opt.get("en") or "").strip()) or PLACEHOLDER_OPT.match(
                        (opt.get(lang) or "").strip()
                    ):
                        errors.append(f"{q.get('id')} cp placeholder")
            # no தொப்பி as leftover bad option in foundation after patch when question is blend/word
            opts_ta = [o.get("ta") for o in q.get("options", [])]
            if "தொப்பி" in opts_ta:
                errors.append(f"{q.get('id')}: leftover தொப்பி in options")
            if path == "foundation":
                validate_foundation_question(q, f"{course['id']} checkpoint/{q.get('id')}", errors)

    return errors


